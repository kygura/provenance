const BOOKKEEPING = `CREATE TABLE IF NOT EXISTS schema_migrations (
  version INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  applied_at TEXT NOT NULL
)`;

/**
 * Pragmas worth knowing about, and where they actually apply:
 *
 *  - `foreign_keys`: per-connection and OFF by default in SQLite, so the local
 *    (`file:` / `:memory:`) client has to set it on every connection it opens.
 *    On remote libSQL (`libsql://`, `https://`) the statement is executed by the
 *    server against a connection we do not own and does not survive the request;
 *    Turso enforces foreign keys server-side, so we simply do not send it there.
 *  - `journal_mode = WAL`: meaningful only for a `file:` database. `:memory:`
 *    ignores it and remote libSQL owns its own durability story.
 *  - `busy_timeout`: local only, and only useful for a `file:` database shared
 *    between processes (the worker and a local dashboard, say).
 *
 * `applyLocalPragmas` is therefore a no-op for remote URLs.
 */
export function isRemoteUrl(url: string): boolean {
  return /^(libsql|https|http|wss|ws):/i.test(url);
}

export async function applyLocalPragmas(client: Client, url: string): Promise<void> {
  if (isRemoteUrl(url)) return;
  await client.execute('PRAGMA foreign_keys = ON');
  if (url.startsWith('file:')) {
    await client.execute('PRAGMA journal_mode = WAL');
    await client.execute('PRAGMA busy_timeout = 5000');
  }
}

/**
 * Applies every migration the database has not seen yet. Safe to call on every
 * boot and from several processes: each migration commits with its own
 * bookkeeping row, and already-applied versions are skipped.
 *
 * Returns the number of migrations applied by this call (0 on a warm database).
 */
export async function migrate(client: Client, logger: Logger = silentLogger): Promise<number> {
  const log = logger.child('migrate');
  await client.execute(BOOKKEEPING);

  const applied = await client.execute('SELECT version FROM schema_migrations');
  const seen = new Set<number>();
  for (const row of applied.rows) {
    const value = row.version;
    if (typeof value === 'number') seen.add(value);
    else if (typeof value === 'bigint') seen.add(Number(value));
  }

  const pending = MIGRATIONS.filter((m) => !seen.has(m.version)).sort((a, b) => a.version - b.version);
  for (const migration of pending) {
    await client.batch(
      [
        ...migration.statements.map((sql) => ({ sql, args: [] })),
        {
          sql: 'INSERT INTO schema_migrations (version, name, applied_at) VALUES (?, ?, ?)',
          args: [migration.version, migration.name, new Date().toISOString()],
        },
      ],
      'write',
    );
    log.info('applied migration', { version: migration.version, name: migration.name });
  }

  return pending.length;
}

/** Renders MIGRATIONS as the flat DDL script kept in `src/schema.sql`. */
export function buildSchemaSql(migrations: readonly Migration[] = MIGRATIONS): string {
  const header = [
    '-- Provenance store schema.',
    '--',
    '-- GENERATED from MIGRATIONS in migrate.ts — do not hand-edit.',
    '--   bun run packages/store/src/migrate.ts --emit-schema',
    '-- packages/store/src/schema.test.ts fails if this file drifts from the code.',
    '--',
    '-- Kept as a readable artefact: `sqlite3 provenance.db < schema.sql` gives a',
    '-- database identical to a fully migrated one, minus the schema_migrations rows.',
    '',
    BOOKKEEPING + ';',
    '',
  ];
  const body = migrations.flatMap((migration) => [
    `-- ===== migration ${String(migration.version).padStart(3, '0')}: ${migration.name} =====`,
    '',
    ...migration.statements.map((sql) => `${sql};\n`),
  ]);
  return `${[...header, ...body].join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

// `bun run packages/store/src/migrate.ts` (wired up as `bun run db:migrate`).
//
// Node APIs rather than Bun globals throughout: this module is imported by the
// Next.js dashboard, which runs on Node under Vercel, so a Bun-only global here
// would break that build even though this block never executes there.
if (import.meta.main) {
  const { loadConfig } = await import('@provenance/core');
  if (process.argv.includes('--emit-schema')) {
    const { writeFile } = await import('node:fs/promises');
    const target = new URL('./schema.sql', import.meta.url);
    await writeFile(target, buildSchemaSql(), 'utf8');
    console.log(`wrote ${target.pathname}`);
  } else {
    const { createStore } = await import('./libsql-store');
    const app = loadConfig();
    const store = createStore(app);
    await store.migrate();
    console.log(`migrated ${app.databaseUrl}`);
    await store.close();
  }
}
