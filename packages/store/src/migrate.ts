/**
 * A single versioned schema step. Statements are applied in order inside one
 * libSQL batch, together with the `schema_migrations` bookkeeping insert, so a
 * migration either lands whole or not at all.
 */
export interface Migration {
  version: number;
  name: string;
  statements: string[];
}

